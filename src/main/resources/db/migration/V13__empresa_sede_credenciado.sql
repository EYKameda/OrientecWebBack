-- V13: Empresa e vínculo organizacional com sede e credenciado.
-- Executar por Flyway junto às demais migrations do Orientec.
CREATE TABLE IF NOT EXISTS empresa (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_legado BIGINT UNIQUE,
    razao_social VARCHAR(180) NOT NULL,
    nome_fantasia VARCHAR(180),
    cnpj VARCHAR(18),
    cpf VARCHAR(14),
    inscricao_estadual VARCHAR(40),
    telefone VARCHAR(40),
    email VARCHAR(180),
    endereco VARCHAR(255),
    numero VARCHAR(20),
    complemento VARCHAR(100),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    uf VARCHAR(2),
    cep VARCHAR(12),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE sede
    ADD COLUMN IF NOT EXISTS empresa_codigo BIGINT;

ALTER TABLE credenciado
    ADD COLUMN IF NOT EXISTS empresa_codigo BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_sede_empresa') THEN
        ALTER TABLE sede ADD CONSTRAINT fk_sede_empresa
            FOREIGN KEY (empresa_codigo) REFERENCES empresa(codigo) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_credenciado_empresa') THEN
        ALTER TABLE credenciado ADD CONSTRAINT fk_credenciado_empresa
            FOREIGN KEY (empresa_codigo) REFERENCES empresa(codigo) ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_sede_empresa ON sede(empresa_codigo);
CREATE INDEX IF NOT EXISTS ix_credenciado_empresa ON credenciado(empresa_codigo);
