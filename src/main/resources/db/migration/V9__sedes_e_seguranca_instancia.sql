CREATE TABLE IF NOT EXISTS sede (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(120) NOT NULL,
    sigla VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_sede_ativo ON sede(ativo);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_sede'
    ) THEN
        ALTER TABLE usuario
            ADD CONSTRAINT fk_usuario_sede
            FOREIGN KEY (sede_codigo) REFERENCES sede(codigo)
            ON DELETE RESTRICT;
    END IF;
END $$;

