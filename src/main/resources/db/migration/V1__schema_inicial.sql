CREATE OR REPLACE FUNCTION validar_autorizador_retrocesso(p_solicitante BIGINT,p_autorizador BIGINT)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
BEGIN
 IF p_solicitante IS NULL OR p_autorizador IS NULL OR p_solicitante=p_autorizador THEN RETURN FALSE; END IF;
 RETURN EXISTS(
  SELECT 1 FROM usuario u
  JOIN usuario_permissao up ON up.usuario_codigo=u.codigo
  JOIN permissao p ON p.id=up.permissao_id
  WHERE u.codigo=p_autorizador AND u.ativo AND p.codigo='OS_RETROCEDER' AND p.ativo
 );
END $$;

CREATE OR REPLACE FUNCTION trg_validar_retrocesso() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NOT validar_autorizador_retrocesso(NEW.usuario_solicitante_codigo,NEW.usuario_autorizador_codigo)
 THEN RAISE EXCEPTION 'Autorizador inválido: deve ser outro usuário ativo com OS_RETROCEDER.'; END IF;
 IF btrim(NEW.justificativa)='' THEN RAISE EXCEPTION 'Justificativa obrigatória.'; END IF;
 RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS tg_validar_retrocesso ON ordem_servico_retrocesso;
CREATE TRIGGER tg_validar_retrocesso BEFORE INSERT ON ordem_servico_retrocesso
FOR EACH ROW EXECUTE FUNCTION trg_validar_retrocesso();

CREATE OR REPLACE FUNCTION trg_proteger_retrocesso() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Histórico de retrocesso é imutável.'; END $$;
DROP TRIGGER IF EXISTS tg_proteger_retrocesso_update ON ordem_servico_retrocesso;
DROP TRIGGER IF EXISTS tg_proteger_retrocesso_delete ON ordem_servico_retrocesso;
CREATE TRIGGER tg_proteger_retrocesso_update BEFORE UPDATE ON ordem_servico_retrocesso
FOR EACH ROW EXECUTE FUNCTION trg_proteger_retrocesso();
CREATE TRIGGER tg_proteger_retrocesso_delete BEFORE DELETE ON ordem_servico_retrocesso
FOR EACH ROW EXECUTE FUNCTION trg_proteger_retrocesso();

