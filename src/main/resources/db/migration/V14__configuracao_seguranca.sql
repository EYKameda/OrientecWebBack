CREATE TABLE IF NOT EXISTS configuracao_seguranca (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    seguranca_ativa BOOLEAN NOT NULL DEFAULT TRUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_por VARCHAR(80)
);

INSERT INTO configuracao_seguranca (id, seguranca_ativa)
VALUES (1, TRUE)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS administrador_configuracao (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(80) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
