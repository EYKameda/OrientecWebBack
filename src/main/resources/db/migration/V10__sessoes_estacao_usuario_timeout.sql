-- Segurança de estação e sessão de usuário.
-- O PMA não possui credencial de usuário; ele autoriza a estação/sede.

ALTER TABLE usuario
    ADD COLUMN IF NOT EXISTS tempo_ocioso_minutos INTEGER NOT NULL DEFAULT 30,
    ADD COLUMN IF NOT EXISTS tempo_maximo_sessao_minutos INTEGER NOT NULL DEFAULT 480;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_usuario_tempo_ocioso') THEN
        ALTER TABLE usuario ADD CONSTRAINT ck_usuario_tempo_ocioso
            CHECK (tempo_ocioso_minutos BETWEEN 1 AND 1440);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_usuario_tempo_max_sessao') THEN
        ALTER TABLE usuario ADD CONSTRAINT ck_usuario_tempo_max_sessao
            CHECK (tempo_maximo_sessao_minutos BETWEEN 30 AND 1440);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS estacao (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sede_codigo BIGINT NOT NULL,
    nome_maquina VARCHAR(120) NOT NULL,
    ip_local VARCHAR(45),
    ip_publico VARCHAR(45),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_heartbeat_em TIMESTAMPTZ,
    CONSTRAINT uk_estacao_sede_maquina UNIQUE (sede_codigo, nome_maquina),
    CONSTRAINT fk_estacao_sede FOREIGN KEY (sede_codigo) REFERENCES sede(codigo) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_estacao_sede_ativo ON estacao(sede_codigo, ativo);

CREATE TABLE IF NOT EXISTS sessao_estacao (
    id UUID PRIMARY KEY,
    estacao_codigo BIGINT NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_heartbeat_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMPTZ NOT NULL,
    encerrada_em TIMESTAMPTZ,
    motivo_encerramento VARCHAR(50),
    ip_local VARCHAR(45),
    ip_publico VARCHAR(45),
    CONSTRAINT fk_sessao_estacao_estacao FOREIGN KEY (estacao_codigo) REFERENCES estacao(codigo) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_sessao_estacao_estacao ON sessao_estacao(estacao_codigo);
CREATE INDEX IF NOT EXISTS ix_sessao_estacao_expira ON sessao_estacao(expira_em);

CREATE TABLE IF NOT EXISTS codigo_lancamento_estacao (
    id UUID PRIMARY KEY,
    sessao_estacao_id UUID NOT NULL,
    codigo_hash VARCHAR(64) NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMPTZ NOT NULL,
    utilizado_em TIMESTAMPTZ,
    CONSTRAINT fk_codigo_lancamento_sessao FOREIGN KEY (sessao_estacao_id) REFERENCES sessao_estacao(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_codigo_lancamento_expira ON codigo_lancamento_estacao(expira_em);

CREATE TABLE IF NOT EXISTS sessao_usuario (
    id UUID PRIMARY KEY,
    usuario_codigo BIGINT NOT NULL,
    sessao_estacao_id UUID NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMPTZ NOT NULL,
    encerrada_em TIMESTAMPTZ,
    motivo_encerramento VARCHAR(50),
    CONSTRAINT fk_sessao_usuario_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario(codigo) ON DELETE RESTRICT,
    CONSTRAINT fk_sessao_usuario_estacao FOREIGN KEY (sessao_estacao_id) REFERENCES sessao_estacao(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_sessao_usuario_usuario ON sessao_usuario(usuario_codigo);
CREATE INDEX IF NOT EXISTS ix_sessao_usuario_expira ON sessao_usuario(expira_em);
CREATE INDEX IF NOT EXISTS ix_sessao_usuario_estacao ON sessao_usuario(sessao_estacao_id);

CREATE TABLE IF NOT EXISTS log_acesso (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(40) NOT NULL,
    resultado VARCHAR(20) NOT NULL,
    usuario_codigo BIGINT,
    login VARCHAR(60),
    sede_codigo BIGINT,
    estacao_codigo BIGINT,
    nome_maquina VARCHAR(120),
    ip_local VARCHAR(45),
    ip_publico VARCHAR(45),
    codigo_motivo VARCHAR(60),
    detalhe_tecnico TEXT,
    CONSTRAINT fk_log_acesso_usuario FOREIGN KEY (usuario_codigo) REFERENCES usuario(codigo) ON DELETE SET NULL,
    CONSTRAINT fk_log_acesso_sede FOREIGN KEY (sede_codigo) REFERENCES sede(codigo) ON DELETE SET NULL,
    CONSTRAINT fk_log_acesso_estacao FOREIGN KEY (estacao_codigo) REFERENCES estacao(codigo) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_log_acesso_ocorrido ON log_acesso(ocorrido_em DESC);
CREATE INDEX IF NOT EXISTS ix_log_acesso_usuario ON log_acesso(usuario_codigo, ocorrido_em DESC);
CREATE INDEX IF NOT EXISTS ix_log_acesso_estacao ON log_acesso(estacao_codigo, ocorrido_em DESC);

